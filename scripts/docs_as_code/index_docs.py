def build_root_index() -> GeneratedIndex:
    """Build the generated root documentation doorway."""
    output_path = DOCS_DIR / "index.md"
    body = [
        "## Purpose",
        "",
        "Root doorway for active Sir Convert-a-Lot documentation.",
        "",
        "## Generated Lanes",
        "",
        "- [Backlog Index](backlog/INDEX.md)",
        "- [Reference Index](reference/INDEX.md)",
        "- [Runbook Index](runbooks/INDEX.md)",
        "",
        "## Authoritative Surfaces",
        "",
        "- [Docs Structure Spec](DOCS_STRUCTURE_SPEC.md)",
        "- [Docs Contract](_meta/docs-contract.yaml)",
        "- [Backlog Guide](backlog/README.md)",
        "- [Converter and API Contracts](converters/)",
        "- [Decisions](decisions/)",
        "- [Product Direction](pdr/)",
    ]
    return render_generated_doc(
        path=output_path,
        frontmatter={
            "type": "spec",
            "id": "SPEC-docs-index",
            "title": "Sir Convert-a-Lot Documentation Index",
            "status": "active",
            "created": existing_created_date(output_path),
            "owners": ["platform"],
            "tags": ["generated", "index"],
        },
        body_lines=body,
    )


def build_generated_indexes() -> list[GeneratedIndex]:
    """Build all generated docs indexes in dependency order."""
    return [
        build_backlog_index(),
        build_reference_index(),
        build_runbook_index(),
        build_root_index(),
    ]


def write_generated_indexes() -> list[Path]:
    """Write all generated indexes and return their paths."""
    written: list[Path] = []
    for generated in build_generated_indexes():
        generated.path.parent.mkdir(parents=True, exist_ok=True)
        generated.path.write_text(generated.content, encoding="utf-8")
        written.append(generated.path)
    return written


def validate_generated_indexes() -> list[str]:
    """Return freshness violations for generated index files."""
    violations: list[str] = []
    for generated in build_generated_indexes():
        if not generated.path.exists():
            violations.append(
                f"{repo_relative(generated.path)}: missing generated index; run `pdm run docs-sync`"
            )
            continue
        actual = generated.path.read_text(encoding="utf-8")
        if actual != generated.content:
            violations.append(
                f"{repo_relative(generated.path)}: stale generated index; run `pdm run docs-sync`"
            )
    return violations


def main() -> None:
    """Regenerate all docs index files."""
    for path in write_generated_indexes():
        print(repo_relative(path))


if __name__ == "__main__":
    main()
